"""Netscape cookie-jar files - the format behind curl's ``-b`` and ``-c``."""

from __future__ import annotations

import time
from http.cookiejar import Cookie, CookieJar
from pathlib import Path

import httpx

from .errors import FileReadError, UsageError

HEADER = "# Netscape HTTP Cookie File\n"
COMMENT = "# This file was generated by curlike. Edit at your own risk.\n"
HTTP_ONLY_PREFIX = "#HttpOnly_"
FAR_FUTURE = 2**31 - 1


def parse_cookie_header(raw: str) -> list[tuple[str, str]]:
    """Split ``-b 'a=1; b=2'`` into pairs. curl also allows commas."""
    pairs: list[tuple[str, str]] = []
    for chunk in raw.replace(",", ";").split(";"):
        name, separator, value = chunk.strip().partition("=")
        if name:
            pairs.append((name, value if separator else ""))
    return pairs


def read(path: str | Path) -> httpx.Cookies:
    """Load a Netscape cookie file. A missing file is an empty jar."""
    target = Path(path)
    try:
        text = target.read_text(encoding="utf-8", errors="surrogateescape")
    except FileNotFoundError:
        return httpx.Cookies()
    except OSError as exc:
        raise FileReadError(f"cannot read cookie file '{target}': {exc.strerror}") from exc
    return httpx.Cookies(_parse(text))


def _parse(text: str) -> CookieJar:
    jar = CookieJar()
    for raw_line in text.splitlines():
        line = raw_line.strip()
        if not line:
            continue

        http_only = line.startswith(HTTP_ONLY_PREFIX)
        if http_only:
            line = line[len(HTTP_ONLY_PREFIX) :]
        elif line.startswith("#"):
            continue

        fields = line.split("\t")
        if len(fields) < 7:
            fields = line.split()
        if len(fields) < 7:
            continue

        domain, include_sub, cookie_path, secure, expires, name, value = fields[:7]
        try:
            expiry = int(expires)
        except ValueError:
            expiry = 0

        rest: dict[str, str | None] = {"HttpOnly": None}
        if http_only:
            rest["HttpOnly"] = True

        jar.set_cookie(
            Cookie(
                version=0,
                name=name,
                value=value,
                port=None,
                port_specified=False,
                domain=domain,
                domain_specified=bool(domain),
                domain_initial_dot=domain.startswith("."),
                path=cookie_path or "/",
                path_specified=bool(cookie_path),
                secure=secure.upper() == "TRUE",
                expires=expiry,
                discard=False,
                comment=None,
                comment_url=None,
                rest=rest,
            )
        )
    return jar


def serialise(cookies: httpx.Cookies) -> str:
    """Render the jar in Netscape format, skipping expired cookies."""
    now = time.time()
    lines = [HEADER, COMMENT]
    for cookie in cookies.jar:
        if cookie.is_expired(now):
            continue
        domain = cookie.domain or ""
        expires = cookie.expires
        if expires is None or expires < now:
            expires = FAR_FUTURE
        lines.append(
            "\t".join(
                [
                    domain,
                    "TRUE" if domain.startswith(".") else "FALSE",
                    cookie.path or "/",
                    "TRUE" if cookie.secure else "FALSE",
                    str(int(expires)),
                    cookie.name,
                    cookie.value,
                ]
            )
            + "\n"
        )
    return "".join(lines)


def write(cookies: httpx.Cookies, destination: str) -> None:
    """Persist the jar. ``-`` means stdout, matching curl."""
    payload = serialise(cookies)
    if destination == "-":
        import sys

        sys.stdout.write(payload)
        sys.stdout.flush()
        return

    target = Path(destination)
    try:
        target.write_text(payload, encoding="utf-8", errors="surrogateescape")
    except OSError as exc:
        raise UsageError(f"cannot write cookie jar '{target}': {exc.strerror}") from exc